-- 2) Tabela de precos por regiao e condicao de pagamento
create table if not exists produtos_precos (
  id uuid primary key default gen_random_uuid(),
  codigo text not null references produtos(codigo) on delete cascade,
  regiao text not null,
  condicao_pagamento text not null,
  preco numeric not null,
  tabela_referencia text,
  atualizado_em timestamptz not null default now(),
